/// Where every document comes from, relative to this crate. Read in full; none is optional.
const DIRECTORIES: &[&str] = &[
    "../../tests/redaction/fixtures",
    "../../tests/redaction/generated",
    "../../tests/conformance/fixtures",
    "../../tests/damaged",
];

/// The recorded outcomes.
const GOLDEN: &str = "../../tests/redaction/outcomes.tsv";

/// The manifest, for the regions it declares.
const MANIFEST: &str = "../../tests/redaction/manifest.toml";

/// `tools/pdfbuild.py`'s `REGION`, `(30, 88, 370, 132)` in PDF space on a 200-point-high page,
/// converted to the display coordinates the operation takes: `(x0, H - y1, x1 - x0, y1 - y0)`.
const PDFBUILD_REGION: Region = Region {
    left: 30.0,
    top: 68.0,
    width: 340.0,
    height: 44.0,
};

/// Larger than any page in the corpus.
const WHOLE_PAGE: Region = Region {
    left: 0.0,
    top: 0.0,
    width: 5000.0,
    height: 5000.0,
};

/// A band across the middle of a letter-sized page, which catches text the other two do not.
const BAND: Region = Region {
    left: 0.0,
    top: 300.0,
    width: 5000.0,
    height: 120.0,
};

/// qpdf, recording the sha256 of every buffer the operation's frame check opens (R10), and
/// whether qpdf's `redact_page` returned bytes.
///
/// Delegates everything; records in `open_output` only, the one method `verify::output` reads the
/// emitted bytes through, and records the argument it then passes on unchanged -- what qpdf does
/// with it after that is the engine's, and `burrow-engines`' `same_bytes_tests` digest that. `fresh`
/// shares the record, because the frame check opens through a fresh engine.
struct Recorder {
    opened: std::rc::Rc<RefCell<Vec<String>>>,
    returned: std::rc::Rc<std::cell::Cell<bool>>,
}

impl PageRedactor for Recorder {
    fn name(&self) -> &'static str {
        PageRedactor::name(&Qpdf)
    }

    fn redact_page(
        &self,
        bytes: &[u8],
        page: usize,
        redacted: &BTreeSet<usize>,
        region: Region,
        options: &OpenOptions<'_>,
    ) -> burrow_types::Result<(Vec<u8>, Report)> {
        let result = Qpdf.redact_page(bytes, page, redacted, region, options);
        self.returned.set(result.is_ok());
        result
    }

    fn input_rotations(
        &self,
        bytes: &[u8],
        options: &OpenOptions<'_>,
        deadline: &Deadline,
    ) -> burrow_types::Result<Vec<i64>> {
        Qpdf.input_rotations(bytes, options, deadline)
    }
}

impl OutputReader for Recorder {
    type Read = <Qpdf as OutputReader>::Read;

    fn fresh(&self) -> Self {
        Self {
            opened: std::rc::Rc::clone(&self.opened),
            returned: std::rc::Rc::clone(&self.returned),
        }
    }

    fn open_output(
        &self,
        bytes: &[u8],
        options: &OpenOptions<'_>,
    ) -> burrow_types::Result<Self::Read> {
        self.opened.borrow_mut().push(hex(bytes));
        Qpdf.fresh().open_output(bytes, options)
    }

    fn page_count(&self, read: &Self::Read) -> burrow_types::Result<u64> {
        OutputReader::page_count(&Qpdf, read)
    }

    fn rotations(
        &self,
        read: &Self::Read,
        options: &OpenOptions<'_>,
        deadline: &Deadline,
    ) -> burrow_types::Result<Vec<i64>> {
        OutputReader::rotations(&Qpdf, read, options, deadline)
    }
}

/// What the recorder saw in one case.
struct Seen {
    /// Whether qpdf's `redact_page` returned bytes, which is what makes the frame check run.
    returned: bool,
    /// The sha256 of each buffer the frame check opened, in order.
    opened: Vec<String>,
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).to_path_buf()
}

fn hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(64);
    for byte in Sha256::digest(bytes) {
        let _ = write!(out, "{byte:02x}");
    }
    out
}

fn options() -> OpenOptions<'static> {
    OpenOptions::new(
        Limits::default(),
        Arc::new(ManualClock::new(0)) as Arc<dyn Clock>,
    )
}

/// Every document, as `(path relative to the repository, bytes)`, sorted.
fn documents() -> Vec<(String, Vec<u8>)> {
    let mut out = Vec::new();
    for directory in DIRECTORIES {
        let path = root().join(directory);
        let mut entries: Vec<PathBuf> = std::fs::read_dir(&path)
            .unwrap_or_else(|error| panic!("{}: {error}", path.display()))
            .filter_map(|entry| entry.ok())
            .map(|entry| entry.path())
            .filter(|path| {
                path.extension()
                    .is_some_and(|extension| extension == "pdf" || extension == "bin")
            })
            .collect();
        entries.sort();
        assert!(
            !entries.is_empty(),
            "{} holds no documents; run tools/check-redaction-corpus.sh first",
            path.display()
        );
        for file in entries {
            let name = format!(
                "{}/{}",
                directory.trim_start_matches("../../"),
                file.file_name().unwrap().to_string_lossy()
            );
            out.push((name, std::fs::read(&file).unwrap()));
        }
    }
    out
}

/// The manifest's `region` for each `file`, keyed by the path this test names documents by.
///
/// Parsed by hand rather than by adding a TOML dependency to a test: only two keys are read, and
/// the count of `region` lines is checked against what was found so a format change fails here
/// instead of silently yielding fewer regions.
fn manifest_regions() -> BTreeMap<String, Region> {
    let text = std::fs::read_to_string(root().join(MANIFEST)).unwrap();
    let mut out = BTreeMap::new();
    let mut region: Option<Region> = None;
    let mut declared = 0usize;
    // A KEY IS WHATEVER PRECEDES ITS `=`, however it is spaced. The first version matched the
    // exact prefix `region = [`, so a `region=[...]` line would have been neither parsed nor
    // counted, and both count assertions below would have passed over it (code review of #191).
    let value_of = |line: &str, key: &str| -> Option<String> {
        let (name, value) = line.split_once('=')?;
        (name.trim() == key).then(|| value.trim().to_owned())
    };
    for line in text.lines() {
        let line = line.trim();
        if line == "[[fixture]]" {
            region = None;
        } else if let Some(value) = value_of(line, "region") {
            declared += 1;
            let Some(inner) = value.strip_prefix('[').and_then(|v| v.strip_suffix(']')) else {
                panic!("a manifest region that is not a one-line array: {line}");
            };
            let numbers: Vec<f64> = inner
                .split(',')
                .map(|n| n.trim().parse().unwrap())
                .collect();
            let [left, top, width, height] = numbers[..] else {
                panic!("a manifest region that is not four numbers: {line}");
            };
            region = Some(Region {
                left,
                top,
                width,
                height,
            });
        } else if let Some(file) = value_of(line, "file")
            && let Some(found) = region.take()
        {
            out.insert(format!("tests/redaction/{}", file.trim_matches('"')), found);
        }
    }
    // Every `region` line precedes its `file` in the manifest; one that did not would be dropped
    // above, and this is what says so.
    assert_eq!(
        out.len(),
        declared,
        "the manifest declares {declared} regions and {} were attributed to a file",
        out.len()
    );
    out
}

/// One case: which page, which pages the operation covers, and which region.
struct Case {
    page: usize,
    covered: BTreeSet<usize>,
    label: &'static str,
    region: Region,
}

fn cases(pages: Option<usize>, manifest: Option<Region>) -> Vec<Case> {
    let mut regions: Vec<(&'static str, Region)> = Vec::new();
    if let Some(region) = manifest {
        regions.push(("manifest", region));
    }
    regions.push(("pdfbuild", PDFBUILD_REGION));
    regions.push(("whole", WHOLE_PAGE));
    regions.push(("band", BAND));

    let mut targets: BTreeSet<usize> = BTreeSet::from([0]);
    if let Some(count) = pages
        && count > 0
    {
        targets.insert(count - 1);
    }
    let mut out = Vec::new();
    // ONE PAST THE END, ONCE. The refusal comes before any region is read, so one region says
    // everything four would.
    if let Some(count) = pages {
        out.push(Case {
            page: count,
            covered: BTreeSet::from([count]),
            label: "whole",
            region: WHOLE_PAGE,
        });
    }
    for page in &targets {
        for (label, region) in &regions {
            out.push(Case {
                page: *page,
                covered: BTreeSet::from([*page]),
                label,
                region: *region,
            });
        }
    }
    if let Some(count) = pages
        && count > 1
    {
        out.push(Case {
            page: 0,
            covered: (0..count).collect(),
            label: "whole",
            region: WHOLE_PAGE,
        });
    }
    out
}

fn covered_label(covered: &BTreeSet<usize>) -> String {
    let all: Vec<String> = covered.iter().map(ToString::to_string).collect();
    all.join(",")
}

/// Run every case, as the lines the golden file holds, and what the recorder saw in each.
fn measure() -> (Vec<String>, usize, Vec<Seen>) {
    let manifest = manifest_regions();
    let documents = documents();
    let mut lines = Vec::new();
    let engine = Recorder {
        opened: std::rc::Rc::new(RefCell::new(Vec::new())),
        returned: std::rc::Rc::new(std::cell::Cell::new(false)),
    };
    let mut seen = Vec::new();
    let mut matched_regions = 0usize;
    for (name, bytes) in &documents {
        lines.push(format!("INPUT\t{name}\t{}", hex(bytes)));
        let pages = Qpdf
            .open(bytes.clone().into_boxed_slice(), &options())
            .and_then(|source| Qpdf.pages(&source))
            .ok()
            .and_then(|count| usize::try_from(count).ok());
        let region = manifest.get(name).copied();
        matched_regions += usize::from(region.is_some());
        for case in cases(pages, region) {
            engine.opened.borrow_mut().clear();
            engine.returned.set(false);
            let result = burrow_ops::redact::page(
                &engine,
                bytes,
                case.page,
                &case.covered,
                case.region,
                &options(),
            );
            seen.push(Seen {
                returned: engine.returned.get(),
                opened: engine.opened.take(),
            });
            let label = format!(
                "{name}\t{}\t{}\t{}",
                case.page,
                covered_label(&case.covered),
                case.label
            );
            let outcome = match result {
                Ok(done) => format!(
                    "OK {} report {}",
                    hex(&done.document),
                    hex(format!("{:?}", done.report).as_bytes())
                ),
                Err(error) => format!("ERR {}", format!("{error:?}").replace(['\n', '\t'], " ")),
            };
            lines.push(format!("CASE\t{label}\t{outcome}"));
        }
    }
    // EVERY REGION THE MANIFEST DECLARES WAS USED, so a renamed fixture cannot quietly fall back
    // to the default region and still match its old outcome by accident.
    assert_eq!(
        matched_regions,
        manifest.len(),
        "the manifest declares {} regions and {matched_regions} matched a document",
        manifest.len()
    );
    (lines, documents.len(), seen)
}

/// R10's gate, per case: a case the golden file records as `OK` had qpdf return bytes and the
/// frame check open exactly one buffer, the document whose digest the row pins; a refused case
/// opened one buffer if the engine had returned bytes and none if it had not. Whether the frame
/// check ran is read from the RUN (`Seen::returned`), not from the refusal's text; the `OK` rows
/// and their digests from the FILE, so a recorder that records nothing cannot agree with itself.
fn read_back_gate(recorded: &[String], seen: &[Seen]) -> Result<String, String> {
    let cases: Vec<(String, String)> = recorded
        .iter()
        .filter(|l| l.starts_with("CASE\t"))
        .map(|line| {
            let (label, outcome) = line
                .strip_prefix("CASE\t")
                .and_then(|rest| rest.rsplit_once('\t'))
                .unwrap_or_default();
            (label.to_owned(), outcome.to_owned())
        })
        .collect();
    let ok = cases.iter().filter(|(_, o)| o.starts_with("OK ")).count();
    let refused_after = cases
        .iter()
        .zip(seen)
        .filter(|((_, o), s)| o.starts_with("ERR ") && s.returned)
        .count();
    let opens: usize = seen.iter().map(|s| s.opened.len()).sum();
    let report = format!(
        "R10 read-backs: {opens} frame-check open(s) over {} cases; expected {} = {ok} OK row(s) \
         in outcomes.tsv + {refused_after} refusal(s) after the engine returned bytes",
        cases.len(),
        ok + refused_after
    );
    if ok == 0 {
        return Err(format!(
            "{report}\nR10: outcomes.tsv records no redacted case, so nothing was measured"
        ));
    }
    if seen.len() != cases.len() {
        return Err(format!(
            "{report}\nR10: the run saw {} case(s) and outcomes.tsv records {}",
            seen.len(),
            cases.len()
        ));
    }
    let mut wrong = Vec::new();
    for ((label, outcome), seen) in cases.iter().zip(seen) {
        let opened = seen.opened.len();
        if let Some(rest) = outcome.strip_prefix("OK ") {
            let pinned = rest.split(' ').next().unwrap_or_default();
            if !seen.returned {
                wrong.push(format!(
                    "{label}: recorded OK, and qpdf's redact_page returned no bytes"
                ));
            } else if seen.opened != [pinned] {
                wrong.push(format!(
                    "{label}: redacted, and the frame check opened {opened} buffer(s), {} of them \
                     the returned document",
                    seen.opened.iter().filter(|o| *o == pinned).count()
                ));
            }
        } else {
            let expected = usize::from(seen.returned);
            if opened != expected {
                let when = if seen.returned { "after" } else { "before" };
                wrong.push(format!(
                    "{label}: refused {when} the engine returned bytes, and the frame check \
                     opened {opened} buffer(s); expected {expected}"
                ));
            }
        }
    }
    if !wrong.is_empty() {
        return Err(format!(
            "{report}\nR10: {} case(s) where the read-back opened the wrong buffers:\n{}",
            wrong.len(),
            wrong.join("\n")
        ));
    }
    Ok(report)
}

/// Every way `computed` differs from `recorded`, named.
fn differences(recorded: &[String], computed: &[String]) -> Vec<String> {
    let key = |line: &String| -> String {
        let fields: Vec<&str> = line.split('\t').collect();
        match fields.first() {
            Some(&"INPUT") => fields[..2].join("\t"),
            _ => fields[..fields.len().saturating_sub(1)].join("\t"),
        }
    };
    let before: BTreeMap<String, &String> = recorded.iter().map(|l| (key(l), l)).collect();
    let after: BTreeMap<String, &String> = computed.iter().map(|l| (key(l), l)).collect();
    let mut out = Vec::new();
    for (k, line) in &before {
        match after.get(k) {
            None => out.push(format!("missing now: {line}")),
            Some(now) if now != line => {
                out.push(format!("changed:\n    was {line}\n    now {now}"));
            }
            Some(_) => {}
        }
    }
    for (k, line) in &after {
        if !before.contains_key(k) {
            out.push(format!("not recorded: {line}"));
        }
    }
    out
}

#[test]
fn every_redaction_outcome_in_the_corpus_is_the_recorded_one() {
    let (computed, documents, seen) = measure();
    let path = root().join(GOLDEN);

    // BLESSING IS ASKED FOR BY NAME, AND NEVER IN CI. `var_os(..).is_some()` blessed on `=0` or an
    // empty value too, and a bless returns before any assertion runs, so a CI job that happened to
    // set it would have rewritten the golden and passed (code review of #191).
    let bless = std::env::var("BURROW_BLESS_REDACTION_OUTCOMES").is_ok_and(|value| value == "1");
    if bless {
        assert!(
            std::env::var_os("CI").is_none(),
            "refusing to bless the redaction outcomes in CI: the golden is the thing CI checks"
        );
        let mut text = String::from(
            "# Every redaction outcome in the corpus, byte for byte. Written by\n\
             # core/burrow-ops/tests/redaction_outcomes.rs under BURROW_BLESS_REDACTION_OUTCOMES=1;\n\
             # see its header for what each line means and when to re-bless.\n",
        );
        for line in &computed {
            text.push_str(line);
            text.push('\n');
        }
        std::fs::write(&path, text).unwrap();
        println!(
            "blessed {} lines over {documents} documents",
            computed.len()
        );
        return;
    }

    let recorded: Vec<String> = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("{}: {error}", path.display()))
        .lines()
        .filter(|line| !line.starts_with('#') && !line.is_empty())
        .map(str::to_owned)
        .collect();

    // THE COUNTS, AND WHAT THEY SHOULD BE. The documents are the directory listing; the cases are
    // what the golden file recorded. Both printed, so a run over fewer reads as fewer.
    let cases = computed.iter().filter(|l| l.starts_with("CASE\t")).count();
    let redacted = computed.iter().filter(|l| l.contains("\tOK ")).count();
    let refused = computed.iter().filter(|l| l.contains("\tERR ")).count();
    let recorded_cases = recorded.iter().filter(|l| l.starts_with("CASE\t")).count();
    let recorded_inputs = recorded.iter().filter(|l| l.starts_with("INPUT\t")).count();
    println!(
        "redaction outcomes: {cases} cases over {documents} documents ({redacted} redacted, \
         {refused} refused); recorded {recorded_cases} cases over {recorded_inputs} documents"
    );
    assert_eq!(
        redacted + refused,
        cases,
        "a case that is neither OK nor ERR"
    );

    let found = differences(&recorded, &computed);
    assert!(
        found.is_empty(),
        "{} of {} recorded lines differ. An INPUT line differing means the fixture changed, not \
         the code; anything else is a behaviour change. Re-bless only if it is meant:\n{}",
        found.len(),
        recorded.len(),
        found.join("\n")
    );
    assert_eq!(recorded_inputs, documents);
    assert_eq!(recorded_cases, cases);

    match read_back_gate(&recorded, &seen) {
        Ok(report) => println!("{report}"),
        Err(refusal) => panic!("{refusal}"),
    }
}

/// The gate refuses each shape of failure, naming it, so a clean run is a measurement.
#[test]
fn the_read_back_gate_names_every_kind_of_failure() {
    let recorded = vec![
        "INPUT\ta.pdf\t00".to_owned(),
        "CASE\ta.pdf\t0\t0\twhole\tOK 11 report 22".to_owned(),
        // THE ENGINE'S OWN VERIFICATION, which shares the frame check's prefix and opens nothing.
        "CASE\ta.pdf\t0\t0\tband\tERR OutputRejected(\"redact: the region is not cleared x\")"
            .to_owned(),
        // THE FRAME CHECK'S REFUSAL, after the engine returned bytes.
        "CASE\ta.pdf\t0\t0\tpdfbuild\tERR OutputRejected(\"redact: burrow produced a document x\")"
            .to_owned(),
        "CASE\ta.pdf\t1\t1\twhole\tERR Malformed(\"pdf redaction [x]: y\")".to_owned(),
    ];
    let seen = |cases: [(bool, &[&str]); 4]| -> Vec<Seen> {
        cases
            .iter()
            .map(|(returned, opened)| Seen {
                returned: *returned,
                opened: opened.iter().map(|o| (*o).to_owned()).collect(),
            })
            .collect()
    };
    let refuses = |seen: &[Seen], reason: &str| {
        let refusal = read_back_gate(&recorded, seen).expect_err(reason);
        assert!(
            refusal.contains(reason),
            "expected {reason:?} in:\n{refusal}"
        );
    };

    let clean = seen([(true, &["11"]), (false, &[]), (true, &["33"]), (false, &[])]);
    let report = read_back_gate(&recorded, &clean).expect("one open per OK row and frame check");
    assert!(
        report.contains("expected 2 = 1 OK row(s) in outcomes.tsv + 1 refusal(s) after"),
        "{report}"
    );

    // AN ENGINE-SIDE REJECTION THAT OPENED THE OUTPUT ANYWAY.
    refuses(
        &seen([
            (true, &["11"]),
            (false, &["44"]),
            (true, &["33"]),
            (false, &[]),
        ]),
        "a.pdf\t0\t0\tband: refused before the engine returned bytes, and the frame check opened \
         1 buffer(s); expected 0",
    );
    // A FRAME-CHECK REFUSAL THAT OPENED NOTHING.
    refuses(
        &seen([(true, &["11"]), (false, &[]), (true, &[]), (false, &[])]),
        "a.pdf\t0\t0\tpdfbuild: refused after the engine returned bytes, and the frame check \
         opened 0 buffer(s); expected 1",
    );
    // A RECORDER THAT RECORDS NOTHING.
    refuses(
        &seen([(true, &[]), (false, &[]), (true, &["33"]), (false, &[])]),
        "a.pdf\t0\t0\twhole: redacted, and the frame check opened 0 buffer(s), 0 of them",
    );
    // ONE TOO MANY.
    refuses(
        &seen([
            (true, &["11", "11"]),
            (false, &[]),
            (true, &["33"]),
            (false, &[]),
        ]),
        "opened 2 buffer(s), 2 of them the returned document",
    );
    // THE WRONG BUFFER, with the count right.
    refuses(
        &seen([(true, &["99"]), (false, &[]), (true, &["33"]), (false, &[])]),
        "opened 1 buffer(s), 0 of them the returned document",
    );
    // AN OK ROW WHOSE ENGINE NEVER RETURNED.
    refuses(
        &seen([
            (false, &["11"]),
            (false, &[]),
            (true, &["33"]),
            (false, &[]),
        ]),
        "recorded OK, and qpdf's redact_page returned no bytes",
    );
    // A RUN OVER FEWER CASES THAN THE FILE.
    let short = clean.into_iter().take(3).collect::<Vec<_>>();
    refuses(&short, "the run saw 3 case(s) and outcomes.tsv records 4");

    // A GOLDEN FILE WITH NOTHING REDACTED is not a measurement, under its own reason.
    let none = vec!["CASE\ta.pdf\t1\t1\twhole\tERR Malformed(\"x\")".to_owned()];
    let refusal = read_back_gate(
        &none,
        &[Seen {
            returned: false,
            opened: Vec::new(),
        }],
    )
    .expect_err("nothing redacted");
    assert!(
        refusal.contains("outcomes.tsv records no redacted case"),
        "{refusal}"
    );
}

/// The comparison sees each kind of difference, so a clean run is a measurement.
#[test]
fn the_comparison_names_every_kind_of_difference() {
    let recorded = vec![
        "INPUT\ta.pdf\t00".to_owned(),
        "CASE\ta.pdf\t0\t0\twhole\tOK 11 report 22".to_owned(),
        "CASE\ta.pdf\t1\t1\twhole\tERR Malformed(\"pdf redaction [x]: y\")".to_owned(),
    ];
    assert!(differences(&recorded, &recorded).is_empty());

    // A different output.
    let mut changed = recorded.clone();
    changed[1] = "CASE\ta.pdf\t0\t0\twhole\tOK 12 report 22".to_owned();
    assert_eq!(differences(&recorded, &changed).len(), 1);

    // The same rule with a different message is a different outcome.
    let mut reworded = recorded.clone();
    reworded[2] = "CASE\ta.pdf\t1\t1\twhole\tERR Malformed(\"pdf redaction [x]: z\")".to_owned();
    assert_eq!(differences(&recorded, &reworded).len(), 1);

    // A refusal that became a redaction.
    let mut flipped = recorded.clone();
    flipped[2] = "CASE\ta.pdf\t1\t1\twhole\tOK 33 report 22".to_owned();
    assert_eq!(differences(&recorded, &flipped).len(), 1);

    // A different input.
    let mut refixtured = recorded.clone();
    refixtured[0] = "INPUT\ta.pdf\t01".to_owned();
    assert_eq!(differences(&recorded, &refixtured).len(), 1);

    // A case gone, and a case new.
    assert_eq!(differences(&recorded, &recorded[..2]).len(), 1);
    let mut grown = recorded.clone();
    grown.push("CASE\ta.pdf\t0\t0\tband\tOK 44 report 22".to_owned());
    assert_eq!(differences(&recorded, &grown).len(), 1);
}
